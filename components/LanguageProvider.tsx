export type TranslationKey = keyof (typeof translations)["es"];

interface LanguageContextValue {
  language: Language;
  toggleLanguage: () => void;
  t: (key: TranslationKey) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

const languageStorageKey = "holos-language";
const languageChangeEvent = "holos-language-change";

function getSavedLanguage(): Language {
  return window.localStorage.getItem(languageStorageKey) === "en" ? "en" : "es";
}

function subscribeToLanguageChange(onChange: () => void) {
  window.addEventListener("storage", onChange);
  window.addEventListener(languageChangeEvent, onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener(languageChangeEvent, onChange);
  };
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const language = useSyncExternalStore<Language>(
    subscribeToLanguageChange,
    getSavedLanguage,
    () => "es",
  );
  const pathname = usePathname();
  const titleKey = pathname === "/servicios"
    ? "site.servicesTitle"
    : pathname === "/nosotros"
      ? "site.aboutTitle"
      : pathname === "/contacto"
        ? "site.contactTitle"
        : pathname === "/privacidad"
          ? "site.privacyTitle"
          : "site.homeTitle";

  useEffect(() => {
    document.documentElement.lang = language === "es" ? "es-MX" : "en";
    document.documentElement.dir = "ltr";
    const title = translations[language][titleKey];
    const syncTitle = () => {
      const titleElements = document.head.querySelectorAll("title");
      const [primaryTitle, ...duplicateTitles] = titleElements;
      if (!primaryTitle) return;
      if (primaryTitle.textContent !== title) primaryTitle.textContent = title;
      duplicateTitles.forEach((element) => element.remove());
    };
    const titleObserver = new MutationObserver(syncTitle);
    titleObserver.observe(document.head, {
      childList: true,
      subtree: true,
      characterData: true,
    });
    syncTitle();
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) description.content = translations[language]["site.description"];
    return () => titleObserver.disconnect();
  }, [language, titleKey]);

  const value: LanguageContextValue = {
    language,
    toggleLanguage: () => {
      window.localStorage.setItem(languageStorageKey, language === "es" ? "en" : "es");
      window.dispatchEvent(new Event(languageChangeEvent));
    },
    t: (key) => translations[language][key],
  };

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
